"""Two separate, externally guarded workers for the experimental junction probe.

No acquisition, video decoding, models, GT, scoring or selected Answer. Root must
hash/register the JSON config and sources before execution and enforce CPU2,
3GiB RSS, 8GiB physical/commit headroom, and the 1830s outer deadline. A prepare
worker exits before the run worker allocates full-window particle genealogy.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

SOURCE_PATHS = (
    "scripts/junction_sequence_probe.py", "monocular_osm/junction_inputs.py",
    "monocular_osm/junction_sequence.py", "monocular_osm/graph_filter.py",
    "monocular_osm/visual_odometry.py", "monocular_osm/road_sign_clues.py",
)
NET_ARRAYS = (
    "origin", "edge_len", "edge_base", "seg_lo", "seg_hi", "seg_gstart",
    "seg_xy0", "seg_dir", "seg_heading", "edge_head_start", "edge_head_end",
    "edge_mid", "reverse_of", "succ_table", "succ_logprior", "succ_head", "xy_max",
    "edge_keys",
)
VO_ARRAYS = ("centers", "xz", "valid", "n_inliers", "rotations", "translations")
MAX_JSON = 16 << 20
MAX_ARCHIVE = 512 << 20


def require(ok, message):
    if not ok:
        raise ValueError(message)


def sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2,
                       allow_nan=False) + "\n").encode("utf-8")


def write_json(path, value):
    with Path(path).open("xb") as stream:
        stream.write(json_bytes(value))


def read_json(path):
    require(Path(path).stat().st_size <= MAX_JSON, "JSON input exceeds 16MiB")
    def bad(value):
        raise ValueError(f"nonfinite JSON constant: {value}")
    return json.loads(Path(path).read_text(encoding="utf-8-sig"), parse_constant=bad)


def checked_ref(ref, base, protected):
    require(isinstance(ref, dict) and set(ref) == {"path", "sha256"}, "exact path/SHA input role required")
    digest = ref["sha256"]
    require(isinstance(digest, str) and len(digest) == 64
            and all(c in "0123456789abcdef" for c in digest), "invalid expected SHA256")
    path = Path(ref["path"])
    path = (base / path if not path.is_absolute() else path).resolve(strict=True)
    require(path.is_file() and sha(path) == digest, f"input bytes differ: {path}")
    old = protected.setdefault(str(path), digest)
    require(old == digest, "one path has conflicting expected hashes")
    return path


def load_config(path, expected, phase):
    path = Path(path).resolve(strict=True)
    require(sha(path) == expected, "configuration file SHA differs")
    config = read_json(path)
    require(config.get("schema") == f"junction-sequence-probe-{phase}-v1", "wrong configuration schema")
    protected = {str(path): expected}
    sources = config.get("source_hashes")
    require(isinstance(sources, dict) and set(SOURCE_PATHS) <= set(sources), "required code-source hashes missing")
    for relative, digest in sources.items():
        source = (ROOT / relative).resolve(strict=True)
        require(source.is_relative_to(ROOT) and source.is_file(), "source role outside executing repository")
        checked_ref({"path": str(source), "sha256": digest}, path.parent, protected)
    require(sha(path) == expected, "configuration changed during source admission")
    return config, path.parent, protected


def verify_files(expected):
    for path, digest in expected.items():
        require(sha(path) == digest, f"protected/generated bytes changed: {path}")


def dependencies():
    import numpy as np
    from monocular_osm import junction_inputs, junction_sequence
    from monocular_osm import graph_filter, visual_odometry, road_sign_clues
    for module in (junction_inputs, junction_sequence, graph_filter, visual_odometry, road_sign_clues):
        require(Path(module.__file__).resolve() == ROOT / (module.__name__.replace(".", "/") + ".py"),
                "foreign module origin")
    return np, junction_inputs, junction_sequence, graph_filter, visual_odometry, road_sign_clues


def load_npz(path):
    import numpy as np
    require(Path(path).stat().st_size <= MAX_ARCHIVE, "NPZ compressed bytes exceed bound")
    with zipfile.ZipFile(path) as archive:
        entries = archive.infolist()
        require(len(entries) <= 64 and len({e.filename for e in entries}) == len(entries)
                and all(e.filename.endswith(".npy") and "/" not in e.filename and "\\" not in e.filename
                        for e in entries)
                and sum(e.file_size for e in entries) <= MAX_ARCHIVE, "NPZ member/storage bound exceeded")
    with np.load(path, allow_pickle=False) as archive:
        arrays = {key: archive[key] for key in archive.files}
    require(all(not a.dtype.hasobject for a in arrays.values()), "object/pickle arrays forbidden")
    return arrays


def typed_sha(array):
    import numpy as np
    require(array.flags.c_contiguous and not array.dtype.hasobject, "plain contiguous array required")
    h = hashlib.sha256(json.dumps([list(array.shape), array.dtype.str], separators=(",", ":")).encode())
    h.update(memoryview(array).cast("B"))
    return h.hexdigest()


def save_npz(path, arrays):
    import numpy as np
    require(all(isinstance(a, np.ndarray) and not a.dtype.hasobject for a in arrays.values()), "NPZ arrays only")
    with Path(path).open("xb") as stream:
        np.savez(stream, **arrays)


def save_network(output, net):
    import numpy as np
    arrays = {name: np.ascontiguousarray(getattr(net, name)) for name in NET_ARRAYS if name != "edge_keys"}
    keys = net.edge_keys
    require(all(len(k) == 3 and all(isinstance(v, (int, np.integer)) and not isinstance(v, (bool, np.bool_))
                                   for v in k) for k in keys), "integer OSM topology edge keys required")
    arrays["edge_keys"] = np.asarray(keys, dtype="<i8").reshape(-1, 3)
    metadata = {"schema": "compact-junction-road-network-v1", "crs": net.crs,
                "allow_uturn": net.allow_uturn, "turn_prior_kappa": net.turn_prior_kappa,
                "normalise_turn_prior": net.normalise_turn_prior,
                "array_sha256": {k: typed_sha(v) for k, v in arrays.items()}, "stats": net.stats()}
    save_npz(output / "network.npz", arrays)
    write_json(output / "network.json", metadata)


def load_network(arrays, metadata, graph_filter):
    import numpy as np
    require(set(arrays) == set(NET_ARRAYS) and metadata.get("schema") == "compact-junction-road-network-v1",
            "compact network member/schema mismatch")
    require(metadata.get("array_sha256") == {k: typed_sha(v) for k, v in arrays.items()}, "network typed bytes differ")
    e, s = len(arrays["edge_len"]), len(arrays["seg_gstart"])
    d = arrays["succ_table"].shape[1] if arrays["succ_table"].ndim == 2 else 0
    require(0 < e <= 100_000 and 0 < s <= 500_000 and 0 < d <= 32, "compact network capacity exceeded")
    shapes = {"origin": (2,), "xy_max": (2,), "edge_keys": (e, 3), "seg_xy0": (s, 2),
              "seg_dir": (s, 2), "edge_mid": (e, 2)}
    shapes.update({k: (s,) for k in ("seg_gstart", "seg_heading")})
    shapes.update({k: (e, d) for k in ("succ_table", "succ_head", "succ_logprior")})
    for key, array in arrays.items():
        require(array.shape == shapes.get(key, (e,)), f"network shape mismatch: {key}")
        integer = key in {"edge_keys", "seg_lo", "seg_hi", "reverse_of", "succ_table"}
        require(array.dtype == np.dtype("int64" if integer else "float64"), f"network dtype mismatch: {key}")
        if key != "succ_logprior":
            require(np.isfinite(array).all(), f"nonfinite network array: {key}")
    successors = arrays["succ_table"]
    require(np.all((successors >= -1) & (successors < e)) and np.count_nonzero(successors >= 0) <= 1_000_000,
            "invalid/unbounded successor indices")
    require(np.all(np.isfinite(arrays["succ_logprior"][successors >= 0]))
            and np.all(np.isneginf(arrays["succ_logprior"][successors < 0])), "invalid turn-prior padding")
    require(np.all(arrays["edge_len"] > 0) and arrays["seg_lo"][0] == 0
            and arrays["seg_hi"][-1] == s and np.all(arrays["seg_hi"] > arrays["seg_lo"])
            and np.array_equal(arrays["seg_hi"][:-1], arrays["seg_lo"][1:]), "invalid edge/segment partition")
    require(metadata.get("allow_uturn") is False and metadata.get("normalise_turn_prior") is False
            and metadata.get("turn_prior_kappa") == 0., "nonprofile road transition configuration")
    kwargs = {k: v for k, v in arrays.items() if k != "edge_keys"}
    kwargs["edge_keys"] = [tuple(map(int, row)) for row in arrays["edge_keys"]]
    return graph_filter.RoadNetwork(crs=metadata["crs"], **kwargs)


def publish(output, phase, protected, generated, details):
    # Membership walk happens BEFORE final expected-byte checks. No discarded
    # late inventory hash pass may mutate bytes after this boundary.
    require({p.name for p in output.iterdir()} == set(generated), "unexpected output membership")
    verify_files({**protected, **{str(output / key): digest for key, digest in generated.items()}})
    master = {"schema": f"junction-sequence-probe-{phase}-freeze-v1", "status": details.pop("status"),
              "artifacts": generated, "protected_hashes": protected, **details,
              "ground_truth_used": False, "selected_answer": None, "accuracy_admitted": False,
              "external_actor_closure_verified": False,
              "resource_enforcement": "Root external CPU2/RSS3GiB/headroom8GiB/outer1830s guard required"}
    write_json(output / f"frozen_{phase}.json", master)
    return master


def prepare(config_path, expected):
    config, base, protected = load_config(config_path, expected, "prepare")
    _, inputs, _, _, _, clues_core = dependencies()
    require(set(config["inputs"]) == {"raw_graphml", "junction_inventory", "temporal_ocr"}, "prepare input roles differ")
    paths = {k: checked_ref(v, base, protected) for k, v in config["inputs"].items()}
    inventory, temporal = read_json(paths["junction_inventory"]), read_json(paths["temporal_ocr"])
    member = config.get("clues_member", "clues")
    require(member is None or member == "clues", "clues_member must be null or clues")
    clues = temporal if member is None else temporal[member]
    require(isinstance(clues, dict), "literal clue result required")
    origin = config.get("origin_video_sha256") if member is None else temporal.get("origin_video_sha256")
    require(isinstance(origin, str) and len(origin) == 64 and all(c in "0123456789abcdef" for c in origin),
            "explicit temporal OCR origin-video SHA required")
    if "origin_video_sha256" in config:
        require(config["origin_video_sha256"] == origin, "config and temporal OCR origins differ")
    plan = inputs.plan_inputs(inventory["plan"]["city"], inventory["plan"]["bbox_wsen"],
                              bbox_source=inventory["plan"]["bbox_source"])
    matched = inputs.annotate_correlations(clues_core.match_motorway_junctions(clues, inventory))
    import osmnx as ox
    owned = {"raw": ox.load_graphml(paths["raw_graphml"])}
    # The adapter's consume/owned mode is intentionally explicit; no monkeypatch
    # to the genuine simplifier, projector, or numerical module.
    net, topology = inputs.prepare_graph(owned.pop("raw"), inventory, matched, plan, copy_graph=False)
    output = Path(config["output_dir"])
    output = (base / output if not output.is_absolute() else output).resolve()
    require(output not in [p.parent for p in paths.values()], "output must be a new separate directory")
    output.mkdir(parents=True, exist_ok=False)
    save_network(output, net)
    del net
    write_json(output / "matched.json", matched)
    write_json(output / "topology_receipt.json", topology)
    write_json(output / "plan.json", plan)
    names = ("network.npz", "network.json", "matched.json", "topology_receipt.json", "plan.json")
    generated = {name: sha(output / name) for name in names}
    return publish(output, "prepare", protected, generated,
                   {"status": "PREPARED_COMPACT_JUNCTION_SEQUENCE_INPUTS_NO_ACCURACY",
                    "config_sha256": expected, "plan_sha256": plan["plan_sha256"],
                    "origin_video_sha256": origin,
                    "preparation_worker_must_exit_before_run": True})


def load_motion(vo, clock_arrays, timestamp_member, video_binding, graph_filter, visual_odometry):
    import numpy as np
    require(set(VO_ARRAYS) | {"cache_signature"} <= set(vo), "signed VO cache lacks original trajectory members")
    times = clock_arrays[timestamp_member]
    n = len(vo["xz"])
    require(times.dtype == np.dtype("float64") and times.shape == (n,) and 2 <= n <= 100_001
            and np.isfinite(times).all() and times[0] >= 0 and np.all(np.diff(times) > 0), "invalid exact native clock")
    shapes = {"centers": (n, 3), "xz": (n, 2), "valid": (n,), "n_inliers": (n,),
              "rotations": (n, 3, 3), "translations": (n, 3)}
    for key in VO_ARRAYS:
        require(vo[key].shape == shapes[key] and np.isfinite(vo[key]).all(), f"invalid VO array: {key}")
        if key in clock_arrays:
            require(vo[key].dtype == clock_arrays[key].dtype and np.array_equal(vo[key], clock_arrays[key]),
                    f"clock artifact and cached trajectory differ: {key}")
    require(vo["valid"].dtype == np.dtype("bool") and vo["n_inliers"].dtype.kind in "iu"
            and np.all(vo["n_inliers"] >= 0), "invalid raw validity/inlier arrays")
    require({"xz", "valid"} <= set(clock_arrays), "native artifact must independently bind xz and valid")
    signature_array = vo["cache_signature"]
    require(signature_array.shape == () and signature_array.dtype.kind == "U", "plain scalar signed cache identity required")
    signature = json.loads(str(signature_array.item()))
    extraction = signature.get("extraction", {})
    require(signature.get("schema") == 2 and signature.get("vo_algo_version") == 3
            and extraction.get("n_frames") == n, "signed cache schema/version/frame count differs")
    stride, fps = extraction.get("stride"), extraction.get("fps")
    require(type(stride) is int and stride > 0 and type(fps) in (float, int)
            and math.isfinite(fps) and fps > 0, "signed nominal extraction interval missing")
    nominal = stride / fps
    intervals = np.diff(times)
    require(np.allclose(intervals, nominal, rtol=1e-5, atol=1e-6), "native clock differs from declared stride/fps")
    require(extraction.get("timestamps_sha256") == hashlib.sha256(np.asarray(times, dtype="<f8").tobytes()).hexdigest(),
            "native clock differs from original signed raw-F64 hash")
    require(isinstance(video_binding, dict) and set(video_binding) == {"path", "size", "sha256"}
            and type(video_binding["size"]) is int and video_binding["size"] > 0
            and isinstance(video_binding["sha256"], str) and len(video_binding["sha256"]) == 64
            and all(c in "0123456789abcdef" for c in video_binding["sha256"]), "frozen full-video binding required")
    video = signature.get("video", {})
    require(video.get("path") == os.path.normcase(str(Path(video_binding["path"]).resolve()))
            and video.get("size") == video_binding["size"], "signed cache video path/size differs from frozen binding")
    trajectory = visual_odometry.Trajectory(**{k: vo[k] for k in VO_ARRAYS})
    odometry = graph_filter.odometry_from_trajectory(trajectory, nominal,
                    heading_source="rotation", adaptive_heading_noise=True)
    odometry.dt = intervals.copy()
    odometry.heading_var = graph_filter.heading_increment_noise(odometry)
    status = np.where(vo["valid"][1:] & (odometry.step > 0), "measured", "unknown")
    return odometry, status, times


def run(config_path, expected):
    config, base, protected = load_config(config_path, expected, "run")
    np, _, sequence, graph_filter, visual_odometry, _ = dependencies()
    require(set(config["inputs"]) == {"prepared", "native_vo", "native_clock"}, "run input roles differ")
    paths = {k: checked_ref(v, base, protected) for k, v in config["inputs"].items()}
    prepared = read_json(paths["prepared"])
    require(prepared.get("schema") == "junction-sequence-probe-prepare-freeze-v1"
            and prepared.get("status") == "PREPARED_COMPACT_JUNCTION_SEQUENCE_INPUTS_NO_ACCURACY",
            "complete compact prepare freeze required")
    require(prepared.get("origin_video_sha256") == config.get("video_binding", {}).get("sha256")
            and isinstance(prepared.get("origin_video_sha256"), str), "OCR and signed-motion video origins differ")
    for relative in SOURCE_PATHS:
        source = str((ROOT / relative).resolve())
        require(prepared["protected_hashes"].get(source) == protected[source], "prepare/run code sources differ")
    expected_names = {"network.npz", "network.json", "matched.json", "topology_receipt.json", "plan.json"}
    require(set(prepared["artifacts"]) == expected_names, "prepared member set differs")
    prepared_paths = {k: checked_ref({"path": str(paths["prepared"].parent / k), "sha256": v}, base, protected)
                      for k, v in prepared["artifacts"].items()}
    net = load_network(load_npz(prepared_paths["network.npz"]), read_json(prepared_paths["network.json"]), graph_filter)
    matched = read_json(prepared_paths["matched.json"])
    odometry, status, times = load_motion(load_npz(paths["native_vo"]), load_npz(paths["native_clock"]),
                                         config.get("timestamp_member", "timestamps"), config.get("video_binding"),
                                         graph_filter, visual_odometry)
    # Real full profile, fixed seed; no per-case particle/step truncation knob.
    result = sequence.align(net, odometry, status, times,
                            matched, config=sequence.Config(particles=50_000, seed=0, inner_s=1800.))
    arrays = {key: value for key, value in result.items() if isinstance(value, np.ndarray)}
    arrays.update(native_times=times, motion_status=status, native_step=odometry.step,
                  native_heading=odometry.heading, native_heading_var=odometry.heading_var, native_dt=odometry.dt)
    metadata = {key: value for key, value in result.items() if not isinstance(value, np.ndarray)}
    metadata.update(array_keys=sorted(arrays), original_native_clock_sha256=typed_sha(times),
                    status_rule="raw valid[1:] AND derived step>0 => measured; otherwise unknown; never stationary",
                    clock_rule="signature extraction stride/fps nonmetric unit_seconds; exact native PTS differences; adaptive noise recomputed",
                    nominal_clock_tolerance={"rtol": 1e-5, "atol_s": 1e-6},
                    full_video_binding=config["video_binding"], video_bytes_opened_or_verified_by_probe=False)
    output = Path(config["output_dir"])
    output = (base / output if not output.is_absolute() else output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    save_npz(output / "result.npz", arrays)
    write_json(output / "result.json", metadata)
    generated = {name: sha(output / name) for name in ("result.npz", "result.json")}
    return publish(output, "run", protected, generated,
                   {"status": "CLOSED_JUNCTION_SEQUENCE_DIAGNOSTIC_NO_ACCURACY",
                    "config_sha256": expected, "numerical_status": result["status"],
                    "profile": sequence.PROFILE})


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=("prepare", "run"))
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--config-sha256", required=True)
    args = parser.parse_args(argv)
    (prepare if args.phase == "prepare" else run)(args.config, args.config_sha256)


if __name__ == "__main__":
    main()
